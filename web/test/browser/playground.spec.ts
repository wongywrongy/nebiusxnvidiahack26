test('synthetic draft editing saves real upload-only rules and persists browser IDs', async ({ page }) => {
  // Only draft generation is synthetic. Save, PATCH, scan and result use the real mock API.
  const draft = JSON.parse(fs.readFileSync('../tests/data/upload-checklist.json', 'utf8'))
  draft.requirements = draft.requirements.map((r: object) => ({ applies_to: [], ...r }))
  await page.route('**/api/specs', async (route) => {
    const response = await route.fetch()
    await route.fulfill({ response, json: { ...(await response.json()), mode: 'live' } })
  })
  await page.route('**/api/specs/draft?*', (route) => route.fulfill({ json: { draft, usage: {} } }))
  await page.goto('/#specs')
  await page.getByLabel('Draft a checklist from a spec PDF').setInputFiles('../tests/data/off-topic.pdf')
  await page.getByRole('button', { name: 'Delete requirement grade' }).click()
  await page.getByLabel('Value for cycles').fill('400000')
  await page.getByLabel('Operator for cycles').selectOption('lte')
  await page.getByLabel('Severity for cycles').selectOption('minor')
  const saving = page.waitForRequest((request) => request.url().endsWith('/api/checklists') && request.method() === 'POST')
  await page.getByRole('button', { name: 'Use this checklist for my uploads' }).click()
  const payload = (await saving).postDataJSON()
  expect(payload.requirements).toHaveLength(1)
  expect(payload.requirements[0]).toMatchObject({ id: 'cycles', operator: 'lte', value: 400000, severity: 'minor' })
  await expect(page.getByText(/is ready in this browser’s upload spec menu/)).toBeVisible()
  await page.screenshot({ path: '/tmp/speccheck-playground-draft.png', fullPage: true })
  await page.getByRole('link', { name: 'Return to Inbox' }).click()
  await page.reload()
  await page.locator('input[type=file]').first().setInputFiles('../tests/data/off-topic.pdf')
  const selector = page.getByLabel('Spec for off-topic.pdf')
  const option = selector.locator('option').filter({ hasText: '08 71 00 Door Hardware · unreviewed draft' })
  const id = await option.getAttribute('value')
  expect(id).toMatch(/^ck-[0-9a-f]{32}$/)
  await selector.selectOption(id!)
  await page.getByRole('button', { name: 'Scan 1 submittal', exact: true }).click()
  await page.getByRole('button', { name: 'Start review', exact: true }).click()
  await expect(page.getByText(/Checked against your draft checklist 08 71 00 Door Hardware \(1 rules, unreviewed\)/)).toBeVisible()
  await expect(page.getByText('Not confirmed from the documents', { exact: true })).toBeVisible()
  await expect(page.getByText('08 71 00 2.1.A', { exact: true })).toBeVisible()
  await page.screenshot({ path: '/tmp/speccheck-playground-draft-review.png', fullPage: true })
  await page.getByRole('button', { name: 'Mark as not checked' }).click()
  await expect(page.getByRole('heading', { name: 'Outcome', exact: true })).toBeVisible()
  await page.screenshot({ path: '/tmp/speccheck-playground-draft-outcome.png', fullPage: true })
})
