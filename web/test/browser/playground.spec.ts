import { test, expect } from '@playwright/test'
import fs from 'node:fs'

test.beforeEach(async ({ page }) => {
  expect((await (await page.request.get('/api/health')).json()).mode).toBe('mock')
  await page.route('**/api/scan', async (route) => {
    await route.continue({ postData: JSON.stringify({ ...route.request().postDataJSON(), delay_ms: 0 }) })
  })
})

test('off-topic upload has a neutral outcome and no approval action', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByText('No submittals handy? Try one:')).toBeVisible()
  await expect(page.getByRole('link', { name: /RectorSeal Metacaulk/ })).toBeVisible()
  await page.locator('input[type=file]').first().setInputFiles('../tests/data/off-topic.pdf')
  await expect(page.getByText('No submittals handy? Try one:')).toHaveCount(0)
  await page.getByLabel('Spec for off-topic.pdf').selectOption('26 51 00')
  await page.getByRole('button', { name: 'Scan 1 submittal', exact: true }).click()
  await page.getByRole('button', { name: 'Start review', exact: true }).click()
  await expect(page.locator('aside').getByText("Doesn't match this spec", { exact: true })).toBeVisible()
  await expect(page.getByText(/None of the .* rules in Interior Lighting found a value/)).toBeVisible()
  await expect(page.getByRole('button', { name: /^Save approval/ })).toHaveCount(0)
  await expect(page.locator('aside summary', { hasText: /checked against/ })).toContainText(/checked against 26 51 00: 0 of \d+ rules matched/)
  await expect.poll(() => page.locator('img').first().evaluate((node) => (node as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  await page.screenshot({ path: '/tmp/speccheck-playground-off-topic.png', fullPage: true })
  await page.getByRole('button', { name: 'Mark as not checked' }).click()
  await expect(page.getByRole('heading', { name: 'Not checked', exact: true })).toBeVisible()
  await expect(page.getByText('0 to return · 0 approved')).toBeVisible()
  await expect(page.getByText('None marked for return.')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Not checked', exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
})

